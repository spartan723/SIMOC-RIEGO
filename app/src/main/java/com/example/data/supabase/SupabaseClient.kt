package com.example.data.supabase

import android.content.Context
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.BufferedReader
import java.io.InputStreamReader
import java.io.OutputStreamWriter
import java.net.HttpURLConnection
import java.net.URL

private const val TAG = "SupabaseClient"

class SupabaseClient(context: Context) {

    private val prefs = context.getSharedPreferences("bombavigia_supabase_prefs", Context.MODE_PRIVATE)

    companion object {
        private const val KEY_URL = "supabase_url"
        private const val KEY_ANON_KEY = "supabase_anon_key"

        val SCHEMA_SQL: String = """
            -- Copia y pega este script en el SQL Editor de tu proyecto Supabase:

            -- 1. Tabla de Estaciones/Dispositivos IoT
            CREATE TABLE IF NOT EXISTS public.stations (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                hardware_model TEXT,
                battery_level DOUBLE PRECISION DEFAULT 100,
                is_active BOOLEAN DEFAULT true,
                last_seen TIMESTAMPTZ DEFAULT now()
            );

            -- 2. Tabla de Lecturas de Telemetría Vibracional
            CREATE TABLE IF NOT EXISTS public.vibration_readings (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                pump_id BIGINT DEFAULT 1,
                device_id TEXT NOT NULL,
                rms DOUBLE PRECISION NOT NULL,
                peak_frequency DOUBLE PRECISION NOT NULL,
                peak_to_peak DOUBLE PRECISION NOT NULL,
                status TEXT NOT NULL,
                is_pump_on BOOLEAN DEFAULT true,
                health_percentage DOUBLE PRECISION DEFAULT 100,
                notes TEXT,
                created_at TIMESTAMPTZ DEFAULT now()
            );

            -- 3. Habilitar lectura/escritura anónima (o configurar según políticas RLS deseadas)
            ALTER TABLE public.stations ENABLE ROW LEVEL SECURITY;
            ALTER TABLE public.vibration_readings ENABLE ROW LEVEL SECURITY;

            CREATE POLICY "Permitir todo a clientes con anon key en stations"
                ON public.stations FOR ALL USING (true) WITH CHECK (true);

            CREATE POLICY "Permitir todo a clientes con anon key en vibration_readings"
                ON public.vibration_readings FOR ALL USING (true) WITH CHECK (true);
        """.trimIndent()
    }

    var supabaseUrl: String
        get() {
            val saved = prefs.getString(KEY_URL, null)?.trim()?.trimEnd('/')
            if (!saved.isNullOrBlank()) return saved
            return com.example.BuildConfig.SUPABASE_URL.trim().trimEnd('/')
        }
        set(value) {
            prefs.edit().putString(KEY_URL, value.trim().trimEnd('/')).apply()
        }

    var supabaseAnonKey: String
        get() {
            val saved = prefs.getString(KEY_ANON_KEY, null)?.trim()
            if (!saved.isNullOrBlank()) return saved
            return com.example.BuildConfig.SUPABASE_PUBLISHABLE_KEY.trim()
        }
        set(value) {
            prefs.edit().putString(KEY_ANON_KEY, value.trim()).apply()
        }

    val isConfigured: Boolean
        get() = supabaseUrl.isNotBlank() && supabaseAnonKey.isNotBlank()

    suspend fun testConnection(): SupabaseConnectionResult = withContext(Dispatchers.IO) {
        if (!isConfigured) {
            return@withContext SupabaseConnectionResult(
                isSuccess = false,
                message = "Configura la URL y la Anon Key de Supabase en ajustes."
            )
        }

        try {
            val endpoint = "$supabaseUrl/rest/v1/stations?select=id&limit=1"
            val url = URL(endpoint)
            val conn = (url.openConnection() as HttpURLConnection).apply {
                requestMethod = "GET"
                connectTimeout = 10000
                readTimeout = 10000
                setRequestProperty("apikey", supabaseAnonKey)
                setRequestProperty("Authorization", "Bearer $supabaseAnonKey")
                setRequestProperty("Accept", "application/json")
            }

            val code = conn.responseCode
            if (code in 200..299) {
                SupabaseConnectionResult(
                    isSuccess = true,
                    message = "¡Conexión a Supabase y tabla 'stations' exitosa!",
                    statusCode = code
                )
            } else if (code == 404) {
                SupabaseConnectionResult(
                    isSuccess = false,
                    message = "Servidor Supabase alcanzado, pero la tabla 'stations' no está creada. Pulsa 'Copiar SQL' y ejecútalo en el SQL Editor de Supabase.",
                    statusCode = code
                )
            } else {
                val errorStream = conn.errorStream ?: conn.inputStream
                val errorMsg = errorStream?.bufferedReader()?.use { it.readText() } ?: "Error HTTP $code"
                SupabaseConnectionResult(
                    isSuccess = false,
                    message = "HTTP $code: $errorMsg",
                    statusCode = code
                )
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error connecting to Supabase", e)
            SupabaseConnectionResult(
                isSuccess = false,
                message = "Error de red: ${e.localizedMessage ?: e.message}"
            )
        }
    }

    suspend fun upsertStation(station: StationCloudRecord): Result<Unit> = withContext(Dispatchers.IO) {
        if (!isConfigured) return@withContext Result.failure(IllegalStateException("Supabase no configurado"))

        try {
            val endpoint = "$supabaseUrl/rest/v1/stations"
            val url = URL(endpoint)
            val json = JSONObject().apply {
                put("id", station.id)
                put("name", station.name)
                put("hardware_model", station.hardwareModel)
                put("battery_level", station.batteryLevel)
                put("is_active", station.isActive)
            }

            val conn = (url.openConnection() as HttpURLConnection).apply {
                requestMethod = "POST"
                connectTimeout = 8000
                readTimeout = 8000
                doOutput = true
                setRequestProperty("apikey", supabaseAnonKey)
                setRequestProperty("Authorization", "Bearer $supabaseAnonKey")
                setRequestProperty("Content-Type", "application/json")
                setRequestProperty("Prefer", "resolution=merge-duplicates")
            }

            OutputStreamWriter(conn.outputStream).use { writer ->
                writer.write(json.toString())
                writer.flush()
            }

            val code = conn.responseCode
            if (code in 200..299) {
                Result.success(Unit)
            } else {
                val err = conn.errorStream?.bufferedReader()?.use { it.readText() } ?: "HTTP $code"
                Log.w(TAG, "Failed to upsert station to Supabase: $err")
                Result.failure(RuntimeException(err))
            }
        } catch (e: Exception) {
            Log.e(TAG, "Exception upserting station to Supabase", e)
            Result.failure(e)
        }
    }

    suspend fun insertReading(reading: SupabaseVibrationPayload): Result<Unit> = withContext(Dispatchers.IO) {
        if (!isConfigured) return@withContext Result.failure(IllegalStateException("Supabase no configurado"))

        try {
            val endpoint = "$supabaseUrl/rest/v1/vibration_readings"
            val url = URL(endpoint)
            val json = JSONObject().apply {
                put("pump_id", reading.pumpId)
                put("device_id", reading.deviceId)
                put("rms", reading.rms)
                put("peak_frequency", reading.peakFrequency)
                put("peak_to_peak", reading.peakToPeak)
                put("status", reading.status)
                put("is_pump_on", reading.isPumpOn)
                put("health_percentage", reading.healthPercentage)
                put("notes", reading.notes)
            }

            val conn = (url.openConnection() as HttpURLConnection).apply {
                requestMethod = "POST"
                connectTimeout = 8000
                readTimeout = 8000
                doOutput = true
                setRequestProperty("apikey", supabaseAnonKey)
                setRequestProperty("Authorization", "Bearer $supabaseAnonKey")
                setRequestProperty("Content-Type", "application/json")
            }

            OutputStreamWriter(conn.outputStream).use { writer ->
                writer.write(json.toString())
                writer.flush()
            }

            val code = conn.responseCode
            if (code in 200..299) {
                Result.success(Unit)
            } else {
                val err = conn.errorStream?.bufferedReader()?.use { it.readText() } ?: "HTTP $code"
                Log.w(TAG, "Failed to insert reading into Supabase: $err")
                Result.failure(RuntimeException(err))
            }
        } catch (e: Exception) {
            Log.e(TAG, "Exception inserting reading into Supabase", e)
            Result.failure(e)
        }
    }

    suspend fun fetchStations(): Result<List<StationCloudRecord>> = withContext(Dispatchers.IO) {
        if (!isConfigured) return@withContext Result.success(emptyList())

        try {
            val endpoint = "$supabaseUrl/rest/v1/stations?select=*&order=last_seen.desc"
            val url = URL(endpoint)
            val conn = (url.openConnection() as HttpURLConnection).apply {
                requestMethod = "GET"
                connectTimeout = 8000
                readTimeout = 8000
                setRequestProperty("apikey", supabaseAnonKey)
                setRequestProperty("Authorization", "Bearer $supabaseAnonKey")
                setRequestProperty("Accept", "application/json")
            }

            val code = conn.responseCode
            if (code in 200..299) {
                val reader = BufferedReader(InputStreamReader(conn.inputStream))
                val body = reader.readText()
                val jsonArray = JSONArray(body)
                val list = mutableListOf<StationCloudRecord>()
                for (i in 0 until jsonArray.length()) {
                    val item = jsonArray.getJSONObject(i)
                    list.add(
                        StationCloudRecord(
                            id = item.optString("id", ""),
                            name = item.optString("name", "Estación"),
                            hardwareModel = item.optString("hardware_model", "Android"),
                            batteryLevel = item.optDouble("battery_level", 100.0),
                            isActive = item.optBoolean("is_active", true),
                            lastSeen = item.optString("last_seen", "")
                        )
                    )
                }
                Result.success(list)
            } else {
                Result.failure(RuntimeException("HTTP $code"))
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
